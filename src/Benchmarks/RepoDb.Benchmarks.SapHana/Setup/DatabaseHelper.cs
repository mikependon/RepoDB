using System;
using System.Text.RegularExpressions;
using Sap.Data.Hana;

namespace RepoDb.Benchmarks.SapHana.Setup
{
    public static class DatabaseHelper
    {
        public static string ConnectionString { get; private set; }

        public static void Initialize(int elementsCount)
        {
            var connectionString = Environment.GetEnvironmentVariable("REPODB_CONSTR", EnvironmentVariableTarget.Process);

            // Port 39041 is the HANA Express tenant ("HXE") database's own SQL port - connecting there
            // directly is required in a Docker setup like this repo's docker-compose.yml: the SYSTEMDB
            // port (39013) redirects clients to the tenant using the container's internal Docker-network
            // address, which isn't reachable from the host.
            ConnectionString = connectionString ?? "Server=127.0.0.1:39041;UserID=SYSTEM;Password=RepoDB2026;Current Schema=REPODB;";

            EnsureSchema();
            CreatePersonTable();
            FillData(elementsCount);
        }

        private static void FillData(int elementsCount)
        {
            const string commandText = @"insert into ""Person"" (""Name"", ""Age"", ""CreatedDateUtc"")
                                        values (REPEAT('x', 128), :element, CURRENT_TIMESTAMP)";

            using var connection = new HanaConnection(ConnectionString);
            connection.Open();

            for (var i = 1; i <= elementsCount; i++)
            {
                var command = new HanaCommand(commandText, connection);
                command.Parameters.Add(new HanaParameter(":element", i));
                command.ExecuteNonQuery();
            }
        }

        public static void Cleanup()
        {
            const string commandText = @"TRUNCATE TABLE ""Person"";";

            using var connection = new HanaConnection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }

        // HANA refuses to even open a connection whose "Current Schema" doesn't exist yet, so the
        // target schema has to be created (if missing) over a connection string with that clause
        // stripped, before ConnectionString itself can be used for anything else.
        private static void EnsureSchema()
        {
            var schemaMatch = Regex.Match(ConnectionString, @"Current Schema\s*=\s*([^;]+)", RegexOptions.IgnoreCase);
            var schemaName = schemaMatch.Success ? schemaMatch.Groups[1].Value.Trim() : "REPODB";
            var bootstrapConnectionString = Regex.Replace(ConnectionString, @"Current Schema\s*=\s*[^;]*;?", "", RegexOptions.IgnoreCase);

            using var connection = new HanaConnection(bootstrapConnectionString);
            connection.Open();

            using var command = connection.CreateCommand();
            command.CommandText = $"SELECT COUNT(*) FROM SYS.SCHEMAS WHERE SCHEMA_NAME = '{schemaName}'";
            var exists = Convert.ToInt32(command.ExecuteScalar()) > 0;

            if (!exists)
            {
                command.CommandText = $"CREATE SCHEMA \"{schemaName}\"";
                command.ExecuteNonQuery();
            }
        }

        // HANA has no CREATE TABLE IF NOT EXISTS - unlike its CREATE TABLE ... IF NOT EXISTS claim,
        // attempting it throws a syntax error - so the table has to be checked for first.
        private static void CreatePersonTable()
        {
            using var connection = new HanaConnection(ConnectionString);
            connection.Open();

            var exists = connection.ExecuteScalar<int>(
                "SELECT COUNT(*) FROM SYS.TABLES WHERE SCHEMA_NAME = CURRENT_SCHEMA AND TABLE_NAME = 'Person'") > 0;

            if (exists)
            {
                return;
            }

            connection.ExecuteNonQuery(@"CREATE TABLE ""Person""
                    (
                        ""Id"" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                        ""Name"" NVARCHAR(128) NOT NULL,
                        ""Age"" INTEGER NOT NULL,
                        ""CreatedDateUtc"" TIMESTAMP NOT NULL,
                        PRIMARY KEY (""Id"")
                    );");
        }
    }
}
