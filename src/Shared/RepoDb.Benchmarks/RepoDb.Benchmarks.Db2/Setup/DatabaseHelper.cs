using System;
using IBM.Data.Db2;

namespace RepoDb.Benchmarks.Db2.Setup
{
    public static class DatabaseHelper
    {
        public static string ConnectionString { get; private set; }

        public static void Initialize(int elementsCount)
        {
            var connectionString = Environment.GetEnvironmentVariable("REPODB_CONSTR", EnvironmentVariableTarget.Process);

            ConnectionString = connectionString ?? "Server=127.0.0.1:50000;Database=repodb;UID=db2inst1;PWD=RepoDB2026;";

            CreatePersonTable();
            FillData(elementsCount);
        }

        private static void FillData(int elementsCount)
        {
            const string commandText = @"INSERT INTO PERSON (NAME, AGE, CREATEDDATEUTC)
                                        VALUES (REPEAT('x', 128), :element, CURRENT_TIMESTAMP)";

            using var connection = new DB2Connection(ConnectionString);
            connection.Open();

            for (var i = 1; i <= elementsCount; i++)
            {
                var command = new DB2Command(commandText, connection);
                command.Parameters.Add(new DB2Parameter("element", i));
                command.ExecuteNonQuery();
            }
        }

        public static void Cleanup()
        {
            const string commandText = "TRUNCATE TABLE PERSON IMMEDIATE";

            using var connection = new DB2Connection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }

        private static void CreatePersonTable()
        {
            using var connection = new DB2Connection(ConnectionString);
            connection.Open();

            var recordCount = connection.ExecuteScalar<int>(
                "SELECT COUNT(*) FROM SYSCAT.TABLES WHERE TABNAME = 'PERSON' AND TABSCHEMA = CURRENT_SCHEMA");
            if (recordCount <= 0)
            {
                connection.ExecuteNonQuery(@"CREATE TABLE PERSON
                    (
                        ID BIGINT NOT NULL GENERATED BY DEFAULT AS IDENTITY,
                        NAME VARCHAR(128) NOT NULL,
                        AGE INTEGER NOT NULL,
                        CREATEDDATEUTC TIMESTAMP NOT NULL,
                        CONSTRAINT PK_PERSON PRIMARY KEY (ID)
                    )");
            }
        }
    }
}
