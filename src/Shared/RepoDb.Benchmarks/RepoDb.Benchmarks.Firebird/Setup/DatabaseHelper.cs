using System;
using FirebirdSql.Data.FirebirdClient;

namespace RepoDb.Benchmarks.Firebird.Setup
{
    public static class DatabaseHelper
    {
        public static string ConnectionString { get; private set; }

        public static void Initialize(int elementsCount)
        {
            var connectionString = Environment.GetEnvironmentVariable("REPODB_CONSTR", EnvironmentVariableTarget.Process);

            // Pooling=false: RECREATE TABLE below needs an exclusive metadata lock on the table. A
            // pooled physical connection handed back out from an earlier run could still be carrying
            // an uncommitted implicit transaction that touched the table, which would collide with
            // this RECREATE TABLE. Disabling pooling guarantees a genuinely fresh session.
            ConnectionString = connectionString ??
                "DataSource=127.0.0.1;Port=3050;Database=/firebird/data/repodb.fdb;User=SYSDBA;Password=RepoDB2026;Charset=UTF8;Pooling=false;";

            CreatePersonTable();
            FillData(elementsCount);
        }

        private static void FillData(int elementsCount)
        {
            const string commandText = @"insert into ""Person"" (""Name"", ""Age"", ""CreatedDateUtc"")
                                        values (RPAD('', 128, 'x'), @element, CURRENT_TIMESTAMP)";

            using var connection = new FbConnection(ConnectionString);
            connection.Open();

            for (var i = 1; i <= elementsCount; i++)
            {
                var command = new FbCommand(commandText, connection);
                command.Parameters.AddWithValue("@element", i);
                command.ExecuteNonQuery();
            }
        }

        public static void Cleanup()
        {
            // Firebird has no TRUNCATE TABLE statement; DELETE FROM is the idiomatic equivalent.
            const string commandText = @"delete from ""Person""";

            using var connection = new FbConnection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }

        private static void CreatePersonTable()
        {
            // RECREATE TABLE is Firebird's idempotent create-or-replace: unlike CREATE TABLE IF NOT
            // EXISTS elsewhere, it unconditionally drops and recreates the table, guaranteeing a clean
            // slate on every run.
            const string commandText = @"RECREATE TABLE ""Person""
                    (
                        ""Id"" BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL,
                        ""Name"" VARCHAR(128) NOT NULL,
                        ""Age"" INTEGER NOT NULL,
                        ""CreatedDateUtc"" TIMESTAMP NOT NULL,
                        CONSTRAINT ""PK_Person"" PRIMARY KEY (""Id"")
                    )";

            using var connection = new FbConnection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }
    }
}
