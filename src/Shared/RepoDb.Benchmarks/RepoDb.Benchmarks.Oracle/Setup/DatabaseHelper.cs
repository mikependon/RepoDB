using System;
using Oracle.ManagedDataAccess.Client;

namespace RepoDb.Benchmarks.Oracle.Setup
{
    public static class DatabaseHelper
    {
        public static string ConnectionString { get; private set; }

        public static void Initialize(int elementsCount)
        {
            var connectionString = Environment.GetEnvironmentVariable("REPODB_CONSTR", EnvironmentVariableTarget.Process);

            ConnectionString = connectionString ?? "User Id=system;Password=RepoDB2026;Data Source=127.0.0.1:1521/FREEPDB1;";

            CreatePersonTable();
            FillData(elementsCount);
        }

        private static void FillData(int elementsCount)
        {
            const string commandText = @"insert into ""Person"" (""Name"", ""Age"", ""CreatedDateUtc"")
                                        values (RPAD('x', 128, 'x'), :element, SYSTIMESTAMP)";

            using var connection = new OracleConnection(ConnectionString);
            connection.Open();

            for (var i = 1; i <= elementsCount; i++)
            {
                using var command = new OracleCommand(commandText, connection);
                command.Parameters.Add("element", i);
                command.ExecuteNonQuery();
            }
        }

        public static void Cleanup()
        {
            const string commandText = @"TRUNCATE TABLE ""Person""";

            using var connection = new OracleConnection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }

        private static void CreatePersonTable()
        {
            const string commandText = @"BEGIN
                    EXECUTE IMMEDIATE '
                        CREATE TABLE ""Person""
                        (
                            ""Id"" NUMBER(19) GENERATED BY DEFAULT AS IDENTITY,
                            ""Name"" VARCHAR2(128),
                            ""Age"" NUMBER(10),
                            ""CreatedDateUtc"" TIMESTAMP(5),
                            CONSTRAINT ""PK_Person"" PRIMARY KEY (""Id"")
                        )';
                EXCEPTION
                    WHEN OTHERS THEN
                        IF SQLCODE != -955 THEN
                            RAISE;
                        END IF;
                END;";

            using var connection = new OracleConnection(ConnectionString);

            connection.Open();
            connection.ExecuteNonQuery(commandText);
        }
    }
}
